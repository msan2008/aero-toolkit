# -----------------------------------------------------------------------------
# Small plotting helper for the V1 app
# -----------------------------------------------------------------------------
def plot_airfoil_and_separation(
    root_chord: float,
    tip_chord: float,
    sweep_angle: float,
    separation_x_over_c: float,
    airfoil_family: str,
) -> plt.Figure:
    """
    Create a simple 2D conceptual wing-section style plot and mark the predicted
    separation location along the normalized chord.

    This is intentionally lightweight for Version 1. It is not a CFD visualization.
    """
    fig, ax = plt.subplots(figsize=(8, 3))

    # Draw a simple normalized chord line
    ax.plot([0, 1], [0, 0], linewidth=3)

    # Mark the separation location
    ax.scatter([separation_x_over_c], [0], s=100)
    ax.axvline(separation_x_over_c, linestyle="--", linewidth=1)

    # Cosmetic labels
    ax.text(
        separation_x_over_c,
        0.08,
        f"x/c = {separation_x_over_c:.3f}",
        ha="center",
        va="bottom",
    )

    ax.set_xlim(0, 1)
    ax.set_ylim(-0.25, 0.35)
    ax.set_xlabel("Normalized chord location (x/c)")
    ax.set_yticks([])
    ax.set_title(
        f"Predicted Flow Separation Location | {airfoil_family.title()} | "
        f"Root chord={root_chord:.2f}, Tip chord={tip_chord:.2f}, Sweep={sweep_angle:.1f}°"
    )
    ax.grid(True, axis="x", alpha=0.3)

    return fig


