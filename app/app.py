# -----------------------------------------------------------------------------
# Sidebar inputs
# -----------------------------------------------------------------------------
st.sidebar.header("Input Parameters")

airfoil_family = st.sidebar.selectbox(
    "Airfoil Family",
    ["symmetric", "cambered", "biomimetic"],
    index=2,
)

if airfoil_family == "biomimetic":
    tubercle_shape_options = ["whale", "biomimetic_v1"]
    default_tubercle_shape_index = 0
    tubercle_disabled = False
    default_amplitude = 26.247
    default_wavelength = 49.607
else:
    tubercle_shape_options = ["none"]
    default_tubercle_shape_index = 0
    tubercle_disabled = True
    default_amplitude = 0.0
    default_wavelength = 0.0

tubercle_shape = st.sidebar.selectbox(
    "Tubercle Shape",
    tubercle_shape_options,
    index=default_tubercle_shape_index,
)

tubercle_amplitude = st.sidebar.number_input(
    "Tubercle Amplitude",
    min_value=0.0,
    max_value=100.0,
    value=float(default_amplitude),
    step=0.1,
    disabled=tubercle_disabled,
)

tubercle_wavelength = st.sidebar.number_input(
    "Tubercle Wavelength",
    min_value=0.0,
    max_value=200.0,
    value=float(default_wavelength),
    step=0.1,
    disabled=tubercle_disabled,
)

root_chord = st.sidebar.number_input(
    "Root Chord",
    min_value=0.1,
    max_value=10.0,
    value=1.0,
    step=0.1,
)

tip_chord = st.sidebar.number_input(
    "Tip Chord",
    min_value=0.1,
    max_value=10.0,
    value=1.0,
    step=0.1,
)

sweep_angle = st.sidebar.number_input(
    "Sweep Angle (degrees)",
    min_value=0.0,
    max_value=80.0,
    value=0.0,
    step=1.0,
)

angle_of_attack = st.sidebar.number_input(
    "Angle of Attack (degrees)",
    min_value=-10.0,
    max_value=30.0,
    value=10.0,
    step=1.0,
)

airspeed = st.sidebar.number_input(
    "Airspeed",
    min_value=0.1,
    max_value=300.0,
    value=30.0,
    step=1.0,
)

# -----------------------------------------------------------------------------
# Build input dict exactly as the model expects
# -----------------------------------------------------------------------------
input_dict = {
    "airfoil_family": airfoil_family,
    "tubercle_amplitude": tubercle_amplitude,
    "tubercle_wavelength": tubercle_wavelength,
    "tubercle_shape": tubercle_shape,
    "root_chord": root_chord,
    "tip_chord": tip_chord,
    "sweep_angle": sweep_angle,
    "angle_of_attack": angle_of_attack,
    "airspeed": airspeed,
}

# -----------------------------------------------------------------------------
# Display current input schema for debugging / clarity
# -----------------------------------------------------------------------------
with st.expander("Show current input dictionary"):
    st.json(input_dict)
    st.write("Expected model feature order:")
    st.write(get_required_feature_columns())

# -----------------------------------------------------------------------------
# Prediction block
# -----------------------------------------------------------------------------
st.subheader("Model Output")

if st.button("Run Prediction", type="primary"):
    try:
        prediction = predict_from_dict(input_dict)
        label = describe_prediction(prediction)

        metric_col1, metric_col2 = st.columns(2)
        metric_col1.metric("Predicted separation_x_over_c", f"{prediction:.4f}")
        metric_col2.metric("Interpretation", label)

        fig = plot_airfoil_and_separation(
            root_chord=root_chord,
            tip_chord=tip_chord,
            sweep_angle=sweep_angle,
            separation_x_over_c=prediction,
            airfoil_family=airfoil_family,
        )
        st.pyplot(fig)

        output_df = pd.DataFrame([input_dict])
        output_df["predicted_separation_x_over_c"] = prediction
        st.write("Prediction record")
        st.dataframe(output_df, use_container_width=True)

    except Exception as e:
        st.error(f"Prediction failed: {e}")
        st.info(
            "Check that the saved .joblib model is present in the models/ folder, "
            "that the model filename matches what inference.py expects, and that "
            "the app inputs match the training feature schema exactly."
        )
else:
    st.info("Adjust the inputs in the sidebar, then click **Run Prediction**.")

